    'Maximum absolute difference: %.4f Hz\n', ...
    maximumAbsoluteDifference ...
);

fprintf( ...
    ['Values matching the paper within ' ...
     '%.3f Hz: %d of %d (%.2f%%)\n'], ...
    exactMatchTolerance, ...
    numberOfApproximatelyMatchingValues, ...
    totalNumberOfValues, ...
    matchingPercentage ...
);

fprintf('\nGroup A comparison file:\n%s\n', groupACsvFile);
fprintf('\nGroup B comparison file:\n%s\n', groupBCsvFile);
fprintf('\nSummary MAT file:\n%s\n', summaryFile);