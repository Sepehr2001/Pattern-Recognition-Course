    tableDirectory, ...
    'step05_groupB_comparison.csv' ...
);

save( ...
    outputFeatureMatFile, ...
    'cad4WindowTrials', ...
    'dominantFrequencyArray', ...
    'dominantAmplitudeArray', ...
    'dominantFrequencyVector', ...
    'dominantAmplitudeVector', ...
    'frequencyErrorVector', ...
    'featuresTable', ...
    'meanDominantFrequencies', ...
    'calculatedGroupA', ...
    'calculatedGroupB', ...
    'paperGroupA', ...
    'paperGroupB', ...
    'differenceGroupA', ...
    'differenceGroupB', ...
    'meanAbsoluteDifference', ...
    'rootMeanSquaredDifference', ...
    'maximumAbsoluteDifference', ...
    'matchingPercentage', ...
    'frequencyAxis', ...
    'searchFrequencies', ...
    'waveletName', ...
    'decompositionLevel', ...
