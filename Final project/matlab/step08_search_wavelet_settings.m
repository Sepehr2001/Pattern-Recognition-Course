        'Mean12Hz' ...
    } ...
));

fprintf('\nBest Group B averages:\n');

disp(array2table( ...
    [groupB(:), bestCalculatedGroupB], ...
    'VariableNames', { ...
        'SubjectID', ...
        'Mean9Hz', ...
        'Mean10Hz', ...
        'Mean11Hz', ...
        'Mean12Hz' ...
    } ...
));

fprintf('\nResults CSV:\n%s\n', outputCsvFile);
fprintf('\nResults MAT:\n%s\n', outputMatFile);